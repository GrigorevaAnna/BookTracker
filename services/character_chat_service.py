class CharacterChatService:
    """Сервис для общения с литературными персонажами"""

    def __init__(self):
        self.api_key = DEEPSEEK_API_KEY
        self.api_url = DEEPSEEK_API_URL

    def get_character_list(self) -> list[Dict]:
        """Возвращает список доступных персонажей"""
        return [
            {
                "id": char["id"],
                "name": char["name"],
                "book_title": char["book"],
                "avatar_url": char["avatar"],
                "last_message": "",
                "last_message_time": 0,
                "unread_count": 0
            }
            for char in CHARACTERS.values()
        ]

    def get_character(self, character_id: str) -> Optional[Dict]:
        """Возвращает информацию о персонаже"""
        return CHARACTERS.get(character_id)

    async def chat_with_character(
            self,
            character_id: str,
            user_message: str,
            chat_history: list[Dict] = None
    ) -> Dict[str, str]:
        """
        Отправляет сообщение персонажу и получает ответ.

        Args:
            character_id: ID персонажа (oblomov, onegin, pechorin)
            user_message: Сообщение пользователя
            chat_history: История диалога (список {"role": "user"/"assistant", "content": "..."})

        Returns:
            {"reply": "ответ персонажа", "character_id": "..."}
        """
        character = CHARACTERS.get(character_id)
        if not character:
            return {"reply": "Персонаж не найден.", "character_id": character_id}

        # Формируем сообщения для нейросети
        messages = [
            {"role": "system", "content": character["system_prompt"]}
        ]

        # Добавляем историю диалога (последние 10 сообщений)
        if chat_history:
            for msg in chat_history[-10:]:
                messages.append({
                    "role": msg.get("role", "user"),
                    "content": msg.get("content", "")
                })

        # Добавляем текущее сообщение
        messages.append({
            "role": "user",
            "content": user_message
        })

        try:
            async with httpx.AsyncClient(timeout=30.0) as client:
                response = await client.post(
                    self.api_url,
                    headers={
                        "Content-Type": "application/json",
                        "Authorization": f"Bearer {self.api_key}"
                    },
                    json={
                        "model": "deepseek-chat",
                        "messages": messages,
                        "temperature": 0.8,
                        "max_tokens": 500
                    }
                )

                if response.status_code == 200:
                    data = response.json()
                    reply = data['choices'][0]['message']['content']

                    return {
                        "reply": reply.strip(),
                        "character_id": character_id
                    }
                else:
                    print(f"❌ DeepSeek ошибка: {response.status_code}")
                    return {
                        "reply": "Прошу прощения... Я сегодня не в духе для разговоров. Зайдите позже.",
                        "character_id": character_id
                    }

        except Exception as e:
            print(f"❌ Ошибка чата: {e}")
            return {
                "reply": "... (молчание) ...",
                "character_id": character_id
            }


